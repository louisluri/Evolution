"""Simulates natural selection in the fictional Neebler population."""
import matplotlib.pyplot as plt
import random

def eat(pop, chance):
    """adds to total population fed this gen based on a percent chance of eating """

    fed = 0
    for each in range(pop):
        if random.randint(1,100) <= chance:
                fed += 1
    return fed

def adjust_to_avail(available, want, subject):
    """adjusts the ammount that want to eat to the ammount of food available if neccesary

    returns the adjusted ammount of the population that got to eat
    *returns a float so you still need to remove remainder
    """

    if available < want:
        subject = (subject * available / want)
    return subject

def ate_died(pop, fed, died):
    """finds out how many that got ate had themselves got food or not, and outputs the 
    adjusted ammount that ate after they survived"""

    if pop == 0:
        return 0  # If population is 0, 'fed' must also be 0

    for each in range(died):
        if random.randint(1,pop) <= fed:
            fed -= 1
    return fed

def reproduce(fed, chance):
    """returns the number of offspring based on how many ate this gen"""

    offspring = 0
    for reproduce in range(fed):
        if random.randint(1,100) <= chance:
            offspring += 1
        else:
            offspring += 0
    return offspring

def hunger(pop, fed, chance):
    """returns the new total alive after killing some of the pop that didnt eat"""

    for didnt_eat in range(pop - fed):
        if random.randint(1,100) <= chance:
            pop -= 1
    return pop

# 1. Enable Interactive Mode
plt.ion()

# 'fig' is the whole window. We create a 1x2 grid of plots.
# ax_line is the first plot (left), ax_bar is the second (right)
fig, (ax_line, ax_bar) = plt.subplots(1, 2, figsize=(16, 7.5))

# Set up the plot aesthetics before the loop
ax_line.set_title("Populations in each Year")
ax_line.set_xlabel("Year (X)")
ax_line.set_ylabel("Pop size (Y)")
ax_line.grid(True) # Add a grid for easier viewing

sizes = ['xxs', 'xs', 's', 'ms', 'm', 'ml', 'l', 'xl', 'xxl']
sizes_rev = list(reversed(sizes)) 

# --- Plotting Data ---
# Use a dictionary to hold the population history lists
pop_history = {size: [] for size in sizes}
pop_history['total'] = []
pop_history['food'] = []
generations = []

# --- Plotting Lines ---
# Use a dictionary to hold the line objects
plot_lines = {}
# Define colors in the same order as 'sizes'
colors = ['indigo', '#8A2BE2', 'b', 'c', 'g', 'y', 'orange', 'r', 'darkred']
labels = ['Sex Panther XXS', 'Extra Small', 'Small', 'Medium Small', 'Medium', 
          'Medium Large', 'Large', 'Extra Large', 'Sex Panther XXL']
abreviated_labels = ['XXS', 'XS', 'S', 'MS', 'M', 'ML', 'L', 'XL', 'XXL']

# Create lines in a loop
for i, size in enumerate(sizes):
    line, = ax_line.plot([], [], color=colors[i], linestyle='-', label=labels[i])
    plot_lines[size] = line
# Add total and food lines separately
plot_lines['total'], = ax_line.plot([], [], color='0.6', linestyle='-', label='Population')
plot_lines['food'], = ax_line.plot([], [], 'k:', label='Food Level')

# Get the handles and labels generated by the plot calls
handles, labels = ax_line.get_legend_handles_labels()

# Reverse both lists
handles.reverse() # Or handles = handles[::-1]
labels.reverse()  # Or labels = labels[::-1]

# Create the legend manually with the reversed items
ax_line.legend(handles, labels, loc='upper left', fontsize=9)

#starting pop
neebler_pops = {size: 5 for size in sizes}
"""{
'xxs': 0, 'xs': 0, 's': 0, 
'ms': 0, 'm': 100, 'ml': 0, 
'l': 0, 'xl': 0, 'xxl': 0
}"""

#edge, all expressed as %
eat_chance = {
'xxs': 98, 'xs': 91, 's': 84, 
'ms': 77, 'm': 70, 'ml': 64, 
'l': 58, 'xl': 52, 'xxl': 46
}

hunt_chance = {
'xxs': 10, 'xs': 12, 's': 14, 
'ms': 16, 'm': 18, 'ml': 20, 
'l': 22, 'xl': 24, 'xxl': 26
}

caught_chance = {
'xxs': 46, 'xs': 52, 's': 58, 
'ms': 64, 'm': 70, 'ml': 76, 
'l': 82, 'xl': 88, 'xxl': 94
}

duplicate_chance = 50

hunger_chance = 50

mutation_chance = 10

#how many tries each prosprctive hunter gets to find an eligable prey
hunt_attempts = 4

#how many steps smaller to be able to eat a creature
steps = 1

#food related hyperparams
food = 200   #start food
growth_rate = 1.5
carrying_capacity = 250
reserve = {
'xxs': 0.42, 'xs': 0.44, 's': 0.46, 
'ms': 0.48, 'm': 0.5, 'ml': 0.52, 
'l': 0.54, 'xl': 0.56, 'xxl': 0.58
}  # % of food that cannot be eaten each year, to stabalize the food replenishment

total_creatures = sum(neebler_pops.values())

for generation in range(1500):

    # Append in a loop
    generations.append(generation + 1)
    pop_history['total'].append(total_creatures)
    pop_history['food'].append(food)
    for size in sizes:
        pop_history[size].append(max(0, neebler_pops[size]))

    # Update the data for ALL line objects
    plot_lines['total'].set_data(generations, pop_history['total'])
    plot_lines['food'].set_data(generations, pop_history['food'])
    for size in sizes:
        plot_lines[size].set_data(generations, pop_history[size])

    # 7. Rescale the axes to fit all data
    ax_line.relim()
    ax_line.autoscale_view()

    # --- NEW: Bar Chart Update ---
    ax_bar.clear()  # Clear the bar chart for the new frame
    
    # 2. Reverse the order of the population variables
    current_pops = [neebler_pops[size] for size in sizes]
    
    # Draw the bar chart with the new order
    ax_bar.bar(abreviated_labels, current_pops, color=colors)

    ax_bar.set_ylim(0, 250)
    
    # Re-set labels (which were also cleared)
    ax_bar.set_title(f"Population at Year {generation + 1}")
    # --- End Bar Chart ---

    # Adjust layout to prevent plots from overlapping
    fig.tight_layout() 
    
    # Pause to allow the plot to update
    plt.pause(0.01) # Use a very short pause for speed

    
    #some hunt
    neeblers_hunted = {size: 0 for size in sizes}
    for size in sizes:
        neeblers_hunted[size] = eat(neebler_pops[size], hunt_chance[size])
    

    done_hunting = {size: 0 for size in sizes}
    killed = {size: 0 for size in sizes}
    failed = {size: 0 for size in sizes}
    max_killable = {size: 0 for size in sizes}

    for size in sizes:
        max_killable[size] = int(neebler_pops[size] * caught_chance[size] / 100)


    #find out who that hunted caught what
    for each in range(max(neeblers_hunted.values())):
    
        for i, size in enumerate(sizes_rev):

            if done_hunting[size] < neeblers_hunted[size]:
                
                #if no possible prey in our sim they can target
                if i + steps > len(sizes_rev) -1:
                    done_hunting[size] = neeblers_hunted[size]
                    failed[size] = neeblers_hunted[size]
                    continue

                prey_possibilitys = sizes_rev[i + steps:]
                attempt = 0
                while attempt < hunt_attempts:
                    rand_prey_size = random.choice(prey_possibilitys)
                    if killed[rand_prey_size] < max_killable[rand_prey_size]:
                        killed[rand_prey_size] += 1
                        attempt = hunt_attempts
                    elif attempt == hunt_attempts - 1:
                        failed[size] += 1
                    attempt += 1
                done_hunting[size] += 1


    for size in sizes:
        neeblers_hunted[size] -= failed[size]
    
    neeblers_herb = {size: 0 for size in sizes}
    for size in sizes:
        neeblers_herb[size] = neebler_pops[size] - neeblers_hunted[size]

    #all try to eat herb
    for size in sizes:
        neeblers_herb[size] = eat(neeblers_herb[size], eat_chance[size])


    # adjust for how much plant food was really available
    want_to_eat_herb = sum(neeblers_herb.values())

    for size in sizes:
        neeblers_herb[size] = adjust_to_avail((food * (1 - reserve[size])), want_to_eat_herb, neeblers_herb[size])

    #move remainders
    remainder = int(sum((neeblers_herb[size] % 1) for size in sizes))
    
    number = 0
    for each in range(remainder):
        trys = 0
        while trys < len(sizes):
            if neebler_pops[sizes[number]] >= 1 and neeblers_herb[sizes[number]] + neeblers_hunted[sizes[number]] < neebler_pops[sizes[number]]:
                neeblers_herb[sizes[number]] += 1
                if number == len(sizes) - 1:
                    number = 0
                else:
                    number += 1
                break
            else:
                if number == len(sizes) - 1:
                    number = 0
                else:
                    number += 1
            trys += 1
        if trys == len(sizes):
            break

    for size in sizes:
        neeblers_herb[size] = int(neeblers_herb[size])

    #subtract any food that was eaten this gen
    food -= sum(neeblers_herb.values())

    #total fed meat and plants
    neeblers_fed = {size: 0 for size in sizes}
    for size in sizes:
        neeblers_fed[size] = neeblers_herb[size] + neeblers_hunted[size]

    #find out how many that ate also died
    for size in sizes:
        neeblers_fed[size] = ate_died(neebler_pops[size], neeblers_fed[size], killed[size])
    
    #subtract from totals too
    for size in sizes:
        neebler_pops[size] -= killed[size]
                

    #neeblers that didnt die and ate have a random chance of reproducing
    offspring = {size: 0 for size in sizes}
    for size in sizes:
        offspring[size] = reproduce(neeblers_fed[size], duplicate_chance)

    #some neeblers that didnt eat can die
    for size in sizes:
        neebler_pops[size] = hunger(neebler_pops[size], neeblers_fed[size], hunger_chance)

    #mutate
    muted = {size: 0 for size in sizes}

    for i, size in enumerate(sizes):
        for kids in range(offspring[size]):
            if random.randint(1,100) <= mutation_chance:
                if i == 0:
                    rand = 1
                elif i == len(sizes) - 1:
                    rand = 100
                else:
                    rand = random.randint(1,100)

                if rand <= 50:
                    offspring[size] -= 1
                    muted[sizes[i + 1]] += 1
                else:
                    offspring[size] -= 1
                    muted[sizes[i - 1]] += 1


    for size in sizes:
        offspring[size] += muted[size]

    #and offspring go on to the next generation
    for size in sizes:
        neebler_pops[size] += offspring[size]
    
    total_creatures = sum(neebler_pops.values())

    #new plant food grows
    food = food + (growth_rate * food * (1 - (food / carrying_capacity)))

    if total_creatures <= 0:
        break


print("The expiremint lasted " + str(generation + 1) + " years")
print("Year " + str(generation + 2) + ":")
print() 
for size in sizes_rev:
    print(str(neebler_pops[size]) + " " + size + " neeblers") 
print()
print(str(int(food)) + " total food")
print(str(total_creatures) + " total creatures")
print()

# Keep the final plot window open
print("Simulation finished.")
plt.ioff()
plt.show()